// Copies the site's color tokens (app/globals.css, in OKLCH) into the app's
// global.css and src/lib/theme.ts, as HSL. Colors with alpha are blended over
// the background, since React Native has no color-mix.
//
//   npm run sync-theme
import { readFileSync, writeFileSync } from 'node:fs';

const KEYS = [
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground',
  'primary', 'primary-foreground', 'brand', 'secondary', 'secondary-foreground',
  'muted', 'muted-foreground', 'accent', 'accent-foreground', 'destructive',
  'success', 'success-foreground', 'warning', 'warning-foreground', 'warning-surface',
  'warning-border', 'highlight', 'surface', 'border', 'border-subtle', 'input', 'ring',
  'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5',
];

const siteCss = readFileSync(new URL('../../../app/globals.css', import.meta.url), 'utf8');

function block(selector) {
  const start = siteCss.indexOf(`\n${selector} {`);
  return siteCss.slice(start, siteCss.indexOf('}', start));
}

function oklchToRgb(L, C, H) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const gamma = (x) => {
    x = Math.min(1, Math.max(0, x));
    return x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
  };
  return [
    gamma(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
    gamma(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
    gamma(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s),
  ];
}

function rgbToHsl([r, g, b]) {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min;
  let h = 0;
  let s = 0;
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1));
    h = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  return `${h.toFixed(1)} ${(s * 100).toFixed(1)}% ${(l * 100).toFixed(1)}%`;
}

function tokens(selector) {
  const raw = {};
  const pattern = /--([a-z0-9-]+):\s*oklch\(([\d.]+) ([\d.]+) ([\d.]+)(?: \/ (\d+)%)?\)/g;
  for (const [, name, L, C, H, alpha] of block(selector).matchAll(pattern)) {
    raw[name] = { rgb: oklchToRgb(+L, +C, +H), alpha: alpha ? +alpha / 100 : 1 };
  }
  const background = raw.background.rgb;
  const out = {};
  for (const key of KEYS) {
    if (!raw[key]) throw new Error(`${selector} has no --${key} in app/globals.css`);
    const { rgb, alpha } = raw[key];
    out[key] = rgbToHsl(rgb.map((c, i) => c * alpha + background[i] * (1 - alpha)));
  }
  return out;
}

const light = tokens(':root');
const dark = tokens('.dark');
const cssVars = (set) => KEYS.map((key) => `    --${key}: ${set[key]};`).join('\n');
const camel = (key) => key.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const tsVars = (set) => KEYS.map((key) => `    ${camel(key)}: 'hsl(${set[key]})',`).join('\n');

writeFileSync(
  new URL('../global.css', import.meta.url),
  `@tailwind base;
@tailwind components;
@tailwind utilities;

/* Generated by scripts/sync-theme.mjs from the site's app/globals.css. */
@layer base {
  :root {
${cssVars(light)}
    --destructive-foreground: 0 0% 100%;
    --radius: 0px;
  }

  .dark:root {
${cssVars(dark)}
    --destructive-foreground: 0 0% 100%;
    --radius: 0px;
  }
}
`,
);

writeFileSync(
  new URL('../src/lib/theme.ts', import.meta.url),
  `import { DarkTheme, DefaultTheme, type Theme } from 'expo-router';

// Generated by scripts/sync-theme.mjs: the same colors as global.css, for
// places that need plain values (navigation, icons, status bar).
export const THEME = {
  light: {
${tsVars(light)}
  },
  dark: {
${tsVars(dark)}
  },
};

export const NAV_THEME: Record<'light' | 'dark', Theme> = {
  light: {
    ...DefaultTheme,
    colors: {
      background: THEME.light.background,
      border: THEME.light.border,
      card: THEME.light.card,
      notification: THEME.light.destructive,
      primary: THEME.light.primary,
      text: THEME.light.foreground,
    },
  },
  dark: {
    ...DarkTheme,
    colors: {
      background: THEME.dark.background,
      border: THEME.dark.border,
      card: THEME.dark.card,
      notification: THEME.dark.destructive,
      primary: THEME.dark.primary,
      text: THEME.dark.foreground,
    },
  },
};
`,
);

